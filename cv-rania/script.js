/* =========================================
   RETOUR À LA LIGNE DES DESCRIPTIONS
========================================= */

function afficherDescription(element, texte) {
  const phrases = texte.match(/[^.!?]+[.!?]+|[^.!?]+$/g) || [];

  element.replaceChildren();

  phrases.forEach((phrase) => {
    const contenu = phrase.trim();

    if (contenu === "") {
      return;
    }

    const ligne = document.createElement("span");

    ligne.textContent = contenu;
    ligne.style.display = "block";
    ligne.style.marginBottom = "3px";
    ligne.style.listStyle = "none";

    element.appendChild(ligne);
  });
}

/* =========================================
   CHANGEMENT DE LANGUE
========================================= */

function changeLanguage(langue) {
  const dictionnaire = translations[langue];

  if (!dictionnaire) {
    return;
  }

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const cle = element.getAttribute("data-i18n");

    if (!Object.prototype.hasOwnProperty.call(dictionnaire, cle)) {
      return;
    }

    const texte = dictionnaire[cle];

    // Sépare les phrases dans les descriptions.
    if (element.classList.contains("description")) {
      afficherDescription(element, texte);
    } else {
      element.textContent = texte;
    }
  });

  document.documentElement.lang = langue;

  document.querySelectorAll(".lang-btn").forEach((bouton) => {
    const actif = bouton.dataset.lang === langue;

    bouton.classList.toggle("active", actif);
    bouton.setAttribute("aria-pressed", String(actif));
  });

  try {
    localStorage.setItem("cv-language", langue);
  } catch (erreur) {
    // Le CV fonctionne même sans stockage.
  }
}

/* =========================================
   DÉMARRAGE DU CV
========================================= */

document.addEventListener("DOMContentLoaded", () => {
  document.querySelectorAll(".lang-btn").forEach((bouton) => {
    bouton.addEventListener("click", () => {
      changeLanguage(bouton.dataset.lang);
    });
  });

  let langueInitiale = "fr";

  try {
    if (localStorage.getItem("cv-language") === "en") {
      langueInitiale = "en";
    }
  } catch (erreur) {
    langueInitiale = "fr";
  }

  changeLanguage(langueInitiale);
});
